// Get complete base pool for a faction
export function getBasesForFaction(faction: PlayableFaction): Base[] {
  switch (faction) {
    case 'rebel':
      return REBEL_BASES;
    case 'empire':
      return EMPIRE_BASES;
    case 'mandalorian':
      return MANDALORIAN_BASES;
    case 'republic':
      return REPUBLIC_BASES;
    case 'separatist':
      return SEPARATIST_BASES;
  }
}

// Helper to construct starting deck
export function createStartingDeck(faction: PlayableFaction): Card[] {
  const cards: Card[] = [];
  if (faction === 'rebel') {
    for (let i = 0; i < 7; i++) cards.push(createCardInstance(ALLIANCE_SHUTTLE));
    for (let i = 0; i < 2; i++) cards.push(createCardInstance(REBEL_TROOPER));
    cards.push(createCardInstance(TEMPLE_GUARDIAN));
  } else if (faction === 'empire') {
    for (let i = 0; i < 7; i++) cards.push(createCardInstance(IMPERIAL_SHUTTLE));
    for (let i = 0; i < 2; i++) cards.push(createCardInstance(STORMTROOPER));
    cards.push(createCardInstance(INQUISITOR));
  } else if (faction === 'mandalorian') {
    for (let i = 0; i < 7; i++) cards.push(createCardInstance(MANDALORIAN_FOUNDLING));
    for (let i = 0; i < 2; i++) cards.push(createCardInstance(MANDALORIAN_WARRIOR));
    cards.push(createCardInstance(CREED_INITIATE));
  } else if (faction === 'republic') {
    for (let i = 0; i < 7; i++) cards.push(createCardInstance(CLONE_CADET));
    for (let i = 0; i < 2; i++) cards.push(createCardInstance(CLONE_TROOPER_P1));
    cards.push(createCardInstance(TEMPLE_PADAWAN));
  } else if (faction === 'separatist') {
    for (let i = 0; i < 7; i++) cards.push(createCardInstance(OOM_PILOT_DROID));
    for (let i = 0; i < 2; i++) cards.push(createCardInstance(B1_BATTLE_DROID));
    cards.push(createCardInstance(SEPARATIST_ACOLYTE));
  }
  return shuffle(cards);
}

// Helper to construct full Galaxy Deck (2 copies of standard cards, 1 of legendary characters)
export function createGalaxyDeck(
  playerFaction?: PlayableFaction,
  botFaction?: PlayableFaction,
  deckType: 'duel' | 'all_eras' = 'duel'
): Card[] {
  let templatesToInclude = ALL_GALAXY_TEMPLATES;
  if (deckType === 'duel' && playerFaction && botFaction) {
    templatesToInclude = ALL_GALAXY_TEMPLATES.filter(
      (t) => t.faction === playerFaction || t.faction === botFaction || t.faction === 'neutral'
    );
  }

  const deck: Card[] = [];
  for (const template of templatesToInclude) {
    const copies = template.uniqueName ? 1 : 2;
    for (let i = 0; i < copies; i++) {
      deck.push(createCardInstance(template));
    }
  }
  return shuffle(deck);
}

// Fisher-Yates shuffle
export function shuffle<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}
