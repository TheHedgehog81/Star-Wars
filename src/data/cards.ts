// Helper to generate unique instance IDs
let nextInstanceId = 1;
export function createCardInstance(template: CardTemplate): Card {
  return {
    ...template,
    instanceId: `card_${template.id}_${nextInstanceId++}_${Math.random().toString(36).substring(2, 6)}`,
    currentDamage: 0,
  };
}

